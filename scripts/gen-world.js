// Generates shared/data/world.js: the full list of selectable countries for travel history.
// Source: world-atlas 50m (Natural Earth). Run: node scripts/gen-world.js
import { readFileSync, writeFileSync } from 'node:fs';
const atlas = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const RENAME = {
  'Macedonia': 'North Macedonia', 'Dominican Rep.': 'Dominican Republic', 'Central African Rep.': 'Central African Republic',
  'Bosnia and Herz.': 'Bosnia and Herzegovina', 'Czechia': 'Czechia', 'Dem. Rep. Congo': 'DR Congo', 'Eq. Guinea': 'Equatorial Guinea',
  'S. Sudan': 'South Sudan', 'Solomon Is.': 'Solomon Islands', 'Falkland Is.': 'Falkland Islands', 'Fr. Polynesia': 'French Polynesia',
  'Marshall Is.': 'Marshall Islands', 'Cayman Is.': 'Cayman Islands', 'Faeroe Is.': 'Faroe Islands', 'Cook Is.': 'Cook Islands',
  'N. Mariana Is.': 'Northern Mariana Islands', 'U.S. Virgin Is.': 'U.S. Virgin Islands', 'British Virgin Is.': 'British Virgin Islands',
  'Turks and Caicos Is.': 'Turks and Caicos Islands', 'St. Vin. and Gren.': 'Saint Vincent and the Grenadines', 'St. Kitts and Nevis': 'Saint Kitts and Nevis',
  'Antigua and Barb.': 'Antigua and Barbuda', 'São Tomé and Principe': 'São Tomé and Príncipe', 'W. Sahara': 'Western Sahara',
  'Fr. S. Antarctic Lands': 'French Southern Lands', 'Heard I. and McDonald Is.': 'Heard and McDonald Islands', 'S. Geo. and the Is.': 'South Georgia',
  'St. Pierre and Miquelon': 'Saint Pierre and Miquelon', 'Wallis and Futuna Is.': 'Wallis and Futuna', 'Pitcairn Is.': 'Pitcairn Islands',
  'Br. Indian Ocean Ter.': 'British Indian Ocean Territory', 'N. Cyprus': null, 'Indian Ocean Ter.': null, 'Siachen Glacier': null,
  'Ashmore and Cartier Is.': null, 'Somaliland': null, 'Antarctica': null, 'Kosovo': 'Kosovo', 'eSwatini': 'Eswatini',
  "Côte d'Ivoire": "Côte d'Ivoire", 'United States of America': 'United States', 'Vatican': 'Vatican City', 'Micronesia': 'Micronesia',
};
const out = [];
for (const g of atlas.objects.countries.geometries) {
  let name = g.properties.name;
  if (name in RENAME) name = RENAME[name];
  if (!name) continue;
  const id = g.id || (name === 'Kosovo' ? 'XKX' : null);
  if (!id) continue;
  out.push({ id, name });
}
out.sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(new URL('../shared/data/world.js', import.meta.url),
  '// AUTO-GENERATED by scripts/gen-world.js from Natural Earth (world-atlas 50m). Do not edit by hand.\n' +
  '// id = ISO 3166-1 numeric code (string), used to match map geometry.\n' +
  'export const WORLD_COUNTRIES = ' + JSON.stringify(out) + ';\n');
console.log('wrote', out.length, 'countries');
